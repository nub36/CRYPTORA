/**
 * CRYPTORA — Серверный мьютекс критической секции скана.
 *
 * ЗАЧЕМ, ЕСЛИ ССЫЛКИ ЗАХВАЧЕНЫ СИНХРОННО
 * ---------------------------------------
 * Скан создаёт СОБСТВЕННЫЙ движок (`new LiveSignalEngine(...)`) и синхронно
 * захватывает его журнал, поэтому известное разделяемое состояние устранено
 * само по себе. Но замороженное ядро устроено так, что часть состояния вообще
 * НЕЛЬЗЯ сделать scan-scoped:
 *
 *   • `LiveSignalEngine` в конструкторе жёстко вызывает
 *     `SignalsAuditLedger.getInstance()` — точки внедрения журнала нет
 *     (`LiveSignalConfig` не содержит поля `ledger`). Значит журнал на один
 *     скан приходится получать через СТАТИЧЕСКИЙ синглтон;
 *   • внутри бандла могут появиться модульные кэши, которые сервер не
 *     контролирует и не видит (сегодня их нет — проверено по src/services,
 *     но гарантии это не даёт).
 *
 * Поэтому поверх scan-scoped контекста стоит мьютекс: он гарантирует, что
 * внутри замороженного ядра в каждый момент находится РОВНО ОДИН скан. Это
 * дешёвая страховка от того, чего сервер не видит.
 *
 * ЧТО ИМЕННО НАХОДИТСЯ ПОД БЛОКИРОВКОЙ
 * ------------------------------------
 *   сброс журнала → создание движка → захват журнала → scanNow() → чтение
 *   журнала и статуса.
 *
 * ЧТО СОЗНАТЕЛЬНО ВНЕ БЛОКИРОВКИ
 * ------------------------------
 *   • предзагрузка свечей — она идёт ДО захвата и попадает в общий кэш
 *     `MarketDataFetcher` с дедупликацией in-flight запросов (`inFlight`),
 *     поэтому параллельные сканы НЕ превращаются в N×запросов к бирже;
 *   • запись в БД (`insertSignal`, `syncSignalLifecycle`) — она не касается
 *     ядра, и держать блокировку на время ввода-вывода значит платить
 *     за чужие транзакции.
 *
 * ПОЧЕМУ ЭТО НЕ «БУРЯ ЗАПРОСОВ»
 * -----------------------------
 * Сериализуется только CPU-фаза оценки, а не сеть. Свечи для всех сканов
 * загружаются общим фетчером с дедупликацией; под блокировкой ядро берёт их
 * из кэша. Платим wall-clock (сканы идут друг за другом), а не нагрузкой на
 * биржу. Выбор сознательный: корректность происхождения сигнала важнее
 * параллельной пропускной способности.
 *
 * Мьютекс — FIFO и никогда не «залипает»: секция освобождается в `finally`,
 * а падение предыдущего скана не мешает следующему.
 */

/** Хвост очереди ожидания. Никогда не находится в состоянии rejected. */
let tail = Promise.resolve();

/** Сколько сканов ждут блокировку прямо сейчас (диагностика и тесты). */
let waiting = 0;

/** Сколько критических секций выполнено с момента старта процесса. */
let acquired = 0;

/**
 * Выполнить `task` в монопольном владении критической секцией скана.
 *
 * @template T
 * @param {() => Promise<T>} task
 * @returns {Promise<T>}
 */
export async function withScanLock(task) {
  const previous = tail;
  waiting += 1;

  let release = () => {};
  tail = new Promise((resolve) => {
    release = resolve;
  });

  try {
    // previous — уже «безопасный» промис (см. ниже), поэтому запускаем task
    // независимо от исхода предыдущего скана: упавший скан не блокирует очередь.
    return await previous.then(task, task);
  } finally {
    waiting -= 1;
    acquired += 1;
    release();
  }
}

/**
 * Состояние мьютекса для диагностики (`/api/admin/strategies/status`) и тестов.
 *
 * @returns {{waiting: number, acquired: number}}
 */
export function scanLockStats() {
  return { waiting, acquired };
}

/**
 * Сброс очереди — ТОЛЬКО для тестов: мьютекс живёт в модуле, а Vitest
 * переиспользует модуль внутри одного файла.
 */
export function __resetScanLockForTests() {
  tail = Promise.resolve();
  waiting = 0;
  acquired = 0;
}
