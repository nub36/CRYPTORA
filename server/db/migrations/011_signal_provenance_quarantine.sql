-- ============================================================================
-- 011: Signal provenance quarantine — аддитивный карантин происхождения
-- ============================================================================
-- Purpose
-- -------
-- Инцидент 2026-09-24: три разных `strategy_id` получили ОДИН и тот же payload
-- (направление / зона входа / стоп / цели) с один и тем же `signal_candle_ts`.
-- Причина — инфраструктурная (см. `docs/incidents/2026-09-24-signal-provenance.md`):
-- разделяемый singleton `SignalsAuditLedger` + параллельные тики планировщика.
-- В БД оказались строки, у которых `strategy_id` (чей это сигнал по записи) не
-- совпадает с `engine_setup_id` (какая стратегия на самом деле его сгенерировала).
--
-- Следствие: 45 строк инцидентной популяции, из которых 30 — доказанно
-- перемаркированы. Считать их в win rate / R / сравнение стратегий НЕЛЬЗЯ: R
-- посчитан чужой стратегией, а приписан другой. Мониторить их тоже нельзя:
-- монитор довёл бы чужой сетап до «исхода» и записал бы исход в историю
-- стратегии, которая этот сетап не создавала.
--
-- Эта миграция НЕ исправляет данные и НЕ удаляет их. Она добавляет КЛАССИФИКАТОР
-- происхождения — по одному признаку, который читается однозначно:
--
--   `engine_setup_id` — это id сетапа, который вернуло ядро. Форма фиксирована
--   (`LiveSignalEngine.ts`, строка создания id):
--
--       `${strategyId}-${symbol.toUpperCase()}-${setupOpenTime}`
--
--   значит префикс до первого `-` — это `strategy_id` ТОЙ СТРАТЕГИИ, КОТОРАЯ
--   РЕАЛЬНО СОЗДАЛА СЕТАП. Сравнение префикса с сохранённым `strategy_id`
--   даёт три исхода:
--
--     префикс == strategy_id  → VERIFIED  (запись согласна с генератором)
--     префикс != strategy_id  → MISMATCH  (строка перемаркирована; доказательство
--                                          прямое: генератор известен и он другой)
--     префикса нет / не читается → UNKNOWN (доказательства нет; НИКОГДА не
--                                          повышается до VERIFIED автоматически)
--
-- Deliberate constraints
-- ----------------------
-- 1. ТОЛЬКО ДОБАВЛЕНИЕ. Ни одна колонка не переименовывается, не удаляется и не
--    меняет тип. Ни одна строка не удаляется (`DELETE` в миграции отсутствует).
-- 2. НЕ ТРОГАЕМ ДАННЫЕ. `strategy_id`, `engine_setup_id`, `hash`,
--    `previous_hash`, `outcome_hash`, `entry_min/max`, `stop_loss`, `targets`
--    этой миграцией не изменяются: они — доказательство, и переписывать их
--    значит уничтожить улики (и нарушить хэш-цепочку).
-- 3. НЕ ТРОГАЕМ ХЭШ-ЦЕПЬ. `provenance_status` — НЕ часть публикуемого payload'а
--    (`hashPayloadV2` в `server/services/signalRepository.js` не изменён),
--    поэтому простановка карантина не меняет ни `hash`, ни `outcome_hash`.
--    Цепочка остаётся валидной ДО и ПОСЛЕ карантина (покрыто тестом).
-- 4. FAIL-CLOSED ПО УМОЛЧАНИЮ. DEFAULT = 'UNKNOWN'. Существующие строки после
--    `ADD COLUMN ... DEFAULT 'UNKNOWN'` классифицируются как «доказательства
--    нет», а не как «всё в порядке». Повышение до VERIFIED возможно только
--    явной процедурой с доказательством (см. `scripts/signal-provenance-classify.mjs`),
--    и только для строк, где префикс `engine_setup_id` совпадает с `strategy_id`.
--    Ошибка в сторону «не мониторим и не считаем» дешевле ошибки в сторону
--    «считаем чужой результат своим».
-- 5. НОВЫЕ СИГНАЛЫ. Код генерации ставит 'VERIFIED' только когда
--    `setup.strategyId === strategyId` запрошенной стратегии — проверка идёт
--    ДО записи в БД, а не после. Строка с расхождением не записывается вовсе.
--
-- Итог: монитор видит только VERIFIED, статистика считает только VERIFIED,
-- MISMATCH и UNKNOWN остаются в таблице как неизменяемое доказательство.
-- ============================================================================

-- ── 1. Классификатор происхождения ────────────────────────────────────────
-- DEFAULT 'UNKNOWN' — fail-closed: отсутствие доказательства не означает
-- согласия. NOT NULL — чтобы `provenance_status IS NULL` не стал четвёртым,
-- неописанным состоянием, которое обойдёт все фильтры.
ALTER TABLE signals ADD COLUMN IF NOT EXISTS provenance_status TEXT NOT NULL DEFAULT 'UNKNOWN';

-- Домен — расширяется двухшагово (NOT VALID → VALIDATE), чтобы не держать
-- ACCESS EXCLUSIVE на время полного сканирования: таблица живёт в production
-- и короткая блокировка на DDL приемлема, длинная — нет.
ALTER TABLE signals DROP CONSTRAINT IF EXISTS signals_provenance_status_check;
ALTER TABLE signals ADD CONSTRAINT signals_provenance_status_check
  CHECK (provenance_status IN ('VERIFIED', 'MISMATCH', 'UNKNOWN')) NOT VALID;
ALTER TABLE signals VALIDATE CONSTRAINT signals_provenance_status_check;

-- ── 2. Индекс под рабочий набор монитора ─────────────────────────────────
-- Монитор читает «открытые И проверенные» — ровно тот же предикат, что и
-- `listOpenSignals()`. Индекс покрывает его без сканирования таблицы.
-- Не CONCURRENTLY: раннер миграций выполняет файл в одной транзакции
-- (BEGIN … COMMIT), а CREATE INDEX CONCURRENTLY в транзакции запрещён.
-- Объём таблицы на момент миграции — десятки строк, короткая блокировка
-- записи дешевле отдельного ручного шага вне транзакции.
CREATE INDEX IF NOT EXISTS idx_signals_provenance_open
  ON signals (provenance_status) WHERE status IN ('ACTIVE', 'FILLED');
