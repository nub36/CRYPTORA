-- ============================================================================
-- 018: signal_lifecycle_events — журнал фактов жизненного цикла сигнала
-- ============================================================================
-- Purpose
-- -------
-- Telegram-уведомления обязаны отражать ПОЛНЫЙ жизненный цикл сигнала
-- (публикация → вход → цели/безубыток → исход), и каждое событие должно
-- приходить пользователю РОВНО ОДИН РАЗ — независимо от 30-секундных тиков
-- монитора, рестартов cryptora.service, повторных сканов и параллельных
-- писателей (монитор позиций + синхронизация скана).
--
-- До этой миграции единственной защитой от дублей была монотонность
-- переходов `signals.status` (`writeLifecycle` возвращает changed только
-- победившему писателю). Это работает для одного перехода, но одно и то же
-- СОБЫТИЕ может быть выведено из РАЗНЫХ переходов: например, FILL выводится
-- и из ACTIVE→FILLED, и из «прямого» ACTIVE→терминал (fill+исход одной
-- записью, когда сделка завершилась до первой синхронизации). Гонка двух
-- таких писателей отправила бы «Вход» дважды.
--
-- Эта таблица — ПЕРСИСТЕНТНЫЙ дедупликатор уровня события:
--   INSERT … ON CONFLICT (signal_id, event_type) DO NOTHING
--   → уведомление отправляет ТОЛЬКО писатель, чей INSERT вставил строку.
-- PK переживает рестарт процесса (никакого in-memory Set), а соревнование
-- двух параллельных INSERT-ов решается самой СУБД.
--
-- Что здесь записывается: только факты frozen-ядра. Терминальные события —
-- из того, что сервер УЖЕ записал в `signals` (переход статуса, fill, исход
-- с exitReason): TP1 доказывается исходом (exitReason TP2 / TP1_THEN_* —
-- правила R2/R3 frozen-ядра), BREAKEVEN — реальным закрытием по безубытку
-- (TP1_THEN_BE / BE). С 2026-10-05 (§6, PR #56) сюда же попадают
-- ПРОМЕЖУТОЧНЫЕ события ОТКРЫТОЙ позиции — TP1/BREAKEVEN из прогресса,
-- который frozen-ядро экспортирует инспекторами того же степпера
-- (inspectTrade/inspectTrailing; прогресс НЕ персистится в signals и
-- переигрывается из closed candles на каждом тике). Прогресс вне
-- frozen-правил никогда не выводится: событие не выдумывается по свечам.
--
-- Deliberate constraints
-- ----------------------
-- 1. ТОЛЬКО ДОБАВЛЕНИЕ. Ни одна существующая таблица/колонка не меняется,
--    данные не перезаписываются, backfill не выполняется: у закрытых строк
--    переходов больше не будет, поэтому повторные уведомления по истории
--    невозможны и без backfill.
-- 2. `occurred_at` — время ФАКТА (бар входа/бар исхода из `signals`),
--    а не время отправки уведомления; NULL = «ядро время не отдало».
--    Выдумывать время запрещено (та же политика, что у `closed_at` в 009).
-- 3. Домен event_type: фиксированные события + шаблон TPn (лестница целей
--    может расти без новой миграции; сегодня frozen-ведение использует
--    TP1/TP2, прочные индексы появляются только с реальной поддержкой
--    со стороны стратегии).
-- 4. Никакой новой торговой механики: таблица — журнал уведомлений о том,
--    что УЖЕ произошло, а не второй источник правды о сделке. Уровни, R и
--    статусы живут в `signals`; здесь только «какие события уже сообщены».
-- ============================================================================

CREATE TABLE IF NOT EXISTS signal_lifecycle_events (
    signal_id   UUID        NOT NULL REFERENCES signals (id) ON DELETE CASCADE,
    event_type  TEXT        NOT NULL,
    occurred_at TIMESTAMPTZ NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (signal_id, event_type),
    CHECK (
        event_type IN ('NEW_SIGNAL', 'FILL', 'BREAKEVEN', 'STOP_LOSS', 'CANCELLED', 'CLOSED')
        OR event_type ~ '^TP[1-9][0-9]*$'
    )
);

COMMENT ON TABLE signal_lifecycle_events IS
    'Журнал фактов жизненного цикла сигнала для дедупликации уведомлений: PK (signal_id, event_type) гарантирует, что событие отправляется ровно один раз — между тиками монитора, рестартами и параллельными писателями.';
COMMENT ON COLUMN signal_lifecycle_events.event_type IS
    'NEW_SIGNAL | FILL | TP1..TPn | BREAKEVEN | STOP_LOSS | CANCELLED (безсделковый терминал до входа) | CLOSED (таймаут/трейлинг и иные закрытия по правилам стратегии).';
COMMENT ON COLUMN signal_lifecycle_events.occurred_at IS
    'Время факта из строки signals (filled_at / closed_at / created_at), а не время отправки. NULL = ядро время не отдало; выдуманное время здесь запрещено.';
